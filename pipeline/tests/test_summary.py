import pytest

from app.summary import amount_snippet, apply_methods, kind_families, support_kinds


@pytest.mark.parametrize(
    "raw,expected",
    [
        ("현금", ["현금"]),
        ("현금(감면)", ["요금·세금 감면"]),
        ("현금||현금(융자)", ["현금", "융자·대출"]),
        ("서비스(의료)||의료지원", ["의료 서비스"]),           # 같은 이름으로 합쳐진다
        ("기타||현금", ["현금"]),                                # 다른 값이 있으면 일반 '기타'는 뺀다
        ("기타", ["기타"]),
        ("새로생긴유형", ["기타"]),                              # 모르는 값은 기타
        ("현금||현물||이용권||시설이용", ["현금", "현물", "이용권"]),  # 최대 3개
        ("", []), (None, []),
    ],
)
def test_support_kinds(raw, expected):
    assert support_kinds(raw) == expected


@pytest.mark.parametrize(
    "raw,expected",
    [
        ("방문신청", ["v"]),
        ("기타 온라인신청||방문신청", ["on", "v"]),
        ("정부24온라인신청||방문신청", ["g", "v"]),
        ("신청불필요", ["n"]),
        ("직접입력", []),                      # 자유 문장은 판단하지 않는다
        ("방문신청||직접입력", ["v"]),
        ("", []), (None, []),
    ],
)
def test_apply_methods(raw, expected):
    assert apply_methods(raw) == expected


@pytest.mark.parametrize(
    "text,expected",
    [
        ("○ 출생아 1인당 200만원 산후조리비용 지원", "1인당 200만원"),
        ("○ 지급금액 : 월 100만원 지급", "월 100만원"),
        ("지원금액 : 가구별 연 70만원, 지역상품권 지급", "연 70만원"),
        ("경영환경 개선 최대 800만원 지원 (총사업비의 80%범위)", "최대 800만원"),
        ("사업화자금 최대1.5억원 지원", "최대 1.5억원"),                  # 붙은 글자를 띄운다
        ("구입비용의 50% 지원(월 5만원 한도)", "월 5만원 한도"),            # '한도'를 함께 보여준다
        ("○ 월 20만 원의 양육수당 지급", "월 20만 원"),
        ("지원기준 : 가구별 연 70만원, 지역상품권 지급", "연 70만원"),    # '지원기준' 은 항목 이름이라 한정 표현이 아니다                    # 원문의 띄어쓰기는 유지
        ("월 30,000원 지급 - 월 30,000원 지급", "월 30,000원"),             # 같은 금액이 반복돼도 하나
    ],
)
def test_amount_extracted_verbatim(text, expected):
    assert amount_snippet(text) == expected


@pytest.mark.parametrize(
    "text",
    [
        None, "", "지원금을 지급합니다",
        "수강료 : 월 27,500원",                                      # 내가 내는 돈
        "월 소득 300만원 이하 가구에 월 20만원 지급",                   # 같은 문장에 소득 기준 -> 안전하게 제외
        "월 300만원 이하 소득자",                                    # 지원 표현 없음
        "매월 34만원~56만원 연령별 차등지원",                          # 범위는 최저값만 보여주게 되므로 제외
        "월 30,000~439,700원 지급",
        "참전유공자 수당 대상자에게 매월 50만원 또는 40만원 지급",   # 뒤의 금액에 앞말이 없어도 서로 다른 금액이면 제외
        "지역별 기준임대료를 상한으로 지원 ㆍ3급지(광역시) 기준 4인 가구 최대 381,000원 지급",   # 특정 지역·가구 기준의 예시
        "자녀 수에 따라 차등 지급 (1인당 월 10만원)",
        "소득별 월 20만원 지급",
        "4인 가구 기준 최대 100만원 지원",
        "월 30만원 지급(청년), 월 15만원 지급(일반)",                  # 서로 다른 금액이 둘 이상
        "본인부담금 월 5만원, 보증금 100만원 납부",
        "대출 한도 최대 5천만원 융자 지원",                            # 대출은 지원금이 아님
        "* 월 10만원 지급(참고)",                                    # 별표 주석
        "지원 : " + "가" * 5 + " 최대 " + "9" * 40 + "만원 지급",     # 문구가 너무 길면 제외
    ],
)
def test_amount_refused_when_unsure(text):
    assert amount_snippet(text) is None


